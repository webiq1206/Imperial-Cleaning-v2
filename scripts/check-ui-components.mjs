// DOM simulation only. No real browser or production network requests.
import assert from 'node:assert/strict';
import React from 'react';
import { JSDOM } from 'jsdom';
const dom=new JSDOM('<!doctype html><html><body></body></html>',{url:'https://imperialcleaninginc.com/idaho/construction-cleaning/boise'});
for(const key of ['window','document','HTMLElement','HTMLInputElement','HTMLTextAreaElement','MutationObserver','Node','Element','Event','MouseEvent'])globalThis[key]=dom.window[key];
Object.defineProperty(globalThis,'navigator',{value:dom.window.navigator,configurable:true});
globalThis.React=React;
globalThis.self=dom.window;
globalThis.requestAnimationFrame=callback=>setTimeout(callback,0);
globalThis.cancelAnimationFrame=id=>clearTimeout(id);
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
process.env.NEXT_PUBLIC_DESIGN_PREVIEW='1';
let networkCalls=0;
globalThis.fetch=async()=>{networkCalls++;throw new Error('Network must remain disabled in component checks');};
const {render,screen,fireEvent,waitFor,cleanup}=await import('@testing-library/react');
const {default:QuoteForm}=await import('../components/quote-form.tsx');
const {default:RfpScorecard}=await import('../components/rfp-scorecard.tsx');
const {default:ResourceBrowser}=await import('../components/resource-browser.tsx');
const {default:ReviewBrowser}=await import('../components/review-browser.tsx');
const {default:HandoverChecklist}=await import('../components/handover-checklist.tsx');
render(React.createElement(QuoteForm));
await waitFor(()=>assert.equal(screen.getByLabelText(/City and state/).value,'Boise, Idaho'));
assert.equal(screen.getByRole('radio',{name:/Construction cleanup/}).checked,true);
fireEvent.click(screen.getByRole('button',{name:/Continue/}));
await screen.findByText('How can we reach you?');
fireEvent.click(screen.getByRole('button',{name:/Back/}));
await screen.findByText('Tell us about your space.');
assert.equal(screen.getByLabelText(/City and state/).value,'Boise, Idaho');
fireEvent.change(screen.getByLabelText(/City and state/),{target:{value:''}});
fireEvent.click(screen.getByRole('button',{name:/Continue/}));
await screen.findByText('Please enter the city and state.');
assert.equal(screen.getByLabelText(/City and state/).getAttribute('aria-invalid'),'true');
cleanup();
console.log('PASS quote service/city preselection, back navigation, required-location validation and accessible errors');
render(React.createElement(RfpScorecard));
for(const input of screen.getAllByRole('spinbutton').filter(input=>input.getAttribute('aria-label').endsWith('rating')))fireEvent.change(input,{target:{value:'5'}});
assert.match(screen.getByRole('status').textContent,/100.0 \/ 100/);
fireEvent.change(screen.getByLabelText('Price weight percent'),{target:{value:'40'}});
assert.match(screen.getByRole('status').textContent,/Adjust weights to total 100%/);
assert.doesNotMatch(screen.getByRole('status').textContent,/Weighted score:/);
fireEvent.click(screen.getByRole('button',{name:'Reset example'}));
assert.match(screen.getByRole('status').textContent,/Weights: 100%/);
cleanup();console.log('PASS RFP score calculation, invalid total guard and reset');
render(React.createElement(ResourceBrowser,{guides:[{slug:'one',title:'Construction tool',description:'First',category:'Construction Cleaning',readTime:'4 min read'},{slug:'two',title:'Buying tool',description:'Second',category:'Buying Guide',readTime:'4 min read'}]}));
fireEvent.click(screen.getByRole('button',{name:'Buying Guide'}));
assert.equal(screen.queryByText('Construction tool'),null);assert.ok(screen.getByText('Buying tool'));cleanup();
render(React.createElement(ReviewBrowser,{reviews:[{author:'Example',rating:5,date:'2026-01-01',source:'Google',sourceUrl:'https://example.test',text:'Unchanged sample text',mentionedServices:['construction-cleaning']}]}));
fireEvent.click(screen.getByRole('button',{name:'Commercial cleaning'}));assert.match(screen.getByRole('status').textContent,/0 reviews/);cleanup();
globalThis.sessionStorage=dom.window.sessionStorage;
render(React.createElement(HandoverChecklist));
const first=screen.getAllByRole('checkbox')[0];fireEvent.click(first);assert.equal(first.checked,true);cleanup();
